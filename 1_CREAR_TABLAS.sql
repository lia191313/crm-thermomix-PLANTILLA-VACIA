create table if not exists public.equipo_notas (
  id         bigint generated by default as identity primary key,
  agente_id  bigint      not null references public.equipo(id) on delete cascade,
  tipo       text        not null default 'nota' check (tipo in ('nota', 'whatsapp', 'llamada', 'venta')),

-- ---------------------------------------------------------------------
-- 1. CONTACTOS (clientes y posibles clientes)
-- ---------------------------------------------------------------------
create table if not exists public.contacts (
  id               bigint generated by default as identity primary key,
  nombre           text      not null default '',
  telefono         text      not null default '',
  ubicacion        text      not null default '',
  modelo           text      not null default '',
  intereses        text[]    not null default '{}',
  notas            text,
  zona_playa       boolean   not null default false,  -- en pantalla: "Mi zona"
  sin_contactar    boolean   not null default false,
  recibe_difusion  boolean   not null default false,  -- "me tiene guardada"
  origen           text,
  estado_lead      text,                              -- paso del Embudo
  recomendada_por  bigint references public.contacts(id) on delete set null,
  created_at       timestamp not null default now(),
  updated_at       timestamp not null default now()
);

-- ---------------------------------------------------------------------
-- 2. HISTORIAL DE CADA CONTACTO (llamadas, notas, WhatsApp, difusiones…)
-- ---------------------------------------------------------------------
create table if not exists public.interactions (
  id          bigint generated by default as identity primary key,
  contact_id  bigint    not null,
  tipo        text      not null default 'nota',
  fecha       timestamp not null default now(),
  notas       text      not null default ''
);
create index if not exists idx_interactions_contact on public.interactions (contact_id);
create index if not exists idx_interactions_fecha   on public.interactions (fecha);

-- ---------------------------------------------------------------------
-- 3. RECORDATORIOS
-- ---------------------------------------------------------------------
create table if not exists public.recordatorios (
  id                     bigint generated by default as identity primary key,
  contacto_id            bigint      not null default 0,   -- 0 = sin contacto
  contacto_nombre        text        not null default '',
  descripcion            text        not null default '',
  fecha                  timestamp,                        -- hora local (España)
  completado             boolean     not null default false,
  tipo                   text,
  frecuencia_dias        integer,
  notas                  text,
  completado_en          timestamptz,
  fecha_ultimo_contacto  timestamptz,
  fecha_programada       timestamptz,
  notified_at            timestamptz,                      -- para avisos al móvil
  created_at             timestamp   not null default now(),
  updated_at             timestamp   not null default now()
);
create index if not exists idx_recordatorios_contacto on public.recordatorios (contacto_id);
create index if not exists idx_recordatorios_pendientes_notificar
  on public.recordatorios (fecha) where completado = false and notified_at is null;

-- ---------------------------------------------------------------------
-- 4. VENTAS
-- ---------------------------------------------------------------------
create table if not exists public.ventas (
  id                    bigint generated by default as identity primary key,
  contacto_id           bigint    not null default 0,
  contacto_nombre       text      not null default '',
  contacto_telefono     text      not null default '',
  contacto_ubicacion    text      not null default '',
  modelo                text      not null default '',
  fecha_venta           date,
  fecha_bienvenida      date,
  bienvenida_realizada  boolean   not null default false,
  notas                 text      not null default '',
  created_at            timestamp not null default now(),
  updated_at            timestamp not null default now()
);

-- ---------------------------------------------------------------------
-- 5. DEMOS
-- ---------------------------------------------------------------------
create table if not exists public.demos (
  id           bigint generated by default as identity primary key,
  contacto_id  bigint    not null default 0,
  fecha_demo   date,
  completada   boolean   not null default false,
  notas        text,
  created_at   timestamp not null default now(),
  updated_at   timestamp not null default now()
);

-- ---------------------------------------------------------------------
-- 6. MARCAS RÁPIDAS SOBRE CONTACTOS
-- ---------------------------------------------------------------------
create table if not exists public.rellamar (
  id               bigint generated by default as identity primary key,
  contact_id       bigint    not null,
  marcado          boolean   not null default true,
  fecha_rellamada  timestamptz,
  created_at       timestamp not null default now()
);
create index if not exists idx_rellamar_contact on public.rellamar (contact_id);

create table if not exists public.rellamadas (
  id           bigint generated by default as identity primary key,
  contacto_id  bigint      not null,
  created_at   timestamptz not null default now()
);

create table if not exists public.prioritarios (
  id           bigint generated by default as identity primary key,
  contacto_id  bigint      not null,
  created_at   timestamptz not null default now()
);

create table if not exists public.dashboard_snooze (
  id             bigint generated by default as identity primary key,
  contact_id     bigint      not null unique,   -- un aplazamiento por contacto
  snoozed_until  timestamptz not null,
  created_at     timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 7. OTRAS SECCIONES (anotaciones, historial de llamadas, grupos, leads)
-- ---------------------------------------------------------------------
create table if not exists public.anotaciones (
  id           bigint generated by default as identity primary key,
  contacto_id  bigint      not null,
  texto        text        not null default '',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists public.historial_llamadas (
  id           bigint generated by default as identity primary key,
  contacto_id  bigint      not null,
  tipo         text        not null default '',
  descripcion  text,
  fecha        timestamptz not null default now(),
  created_at   timestamptz not null default now()
);

create table if not exists public.grupos (
  id           bigint generated by default as identity primary key,
  nombre       text        not null,
  descripcion  text,
  color        text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists public.contacto_grupos (
  id           bigint generated by default as identity primary key,
  contacto_id  bigint      not null,
  grupo_id     bigint      not null references public.grupos(id) on delete cascade,
  created_at   timestamptz not null default now(),
  unique (contacto_id, grupo_id)
);

create table if not exists public.leads_redes (
  id              bigint generated by default as identity primary key,
  nombre          text        not null default '',
  alias           text,
  telefono        text,
  plataforma      text        not null default '',
  estado          text        not null default 'nuevo',
  enlace_anuncio  text,
  notas           text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 8. LISTADOS de posibles clientes (fotos de listados, ferias…)
-- ---------------------------------------------------------------------
create table if not exists public.listados (
  id          bigint generated by default as identity primary key,
  nombre      text        not null,
  created_at  timestamptz not null default now()
);

create table if not exists public.listado_personas (
  id              bigint generated by default as identity primary key,
  listado_id      bigint references public.listados(id) on delete set null,
  nombre          text        not null default '',
  apellidos       text        not null default '',
  telefono        text        not null default '',
  poblacion       text        not null default '',
  estado          text        not null default 'pendiente'
                  check (estado in ('pendiente', 'adoptado', 'descartado', 'comercial')),
  notas           text,
  llamadas        integer     not null default 0,
  ultima_llamada  timestamptz,
  contact_id      bigint,
  rellamar_el     date,
  franja          text check (franja in ('manana', 'tarde')),
  rellamar_hora   time,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists idx_listado_personas_listado  on public.listado_personas (listado_id);
create index if not exists idx_listado_personas_telefono on public.listado_personas (telefono);
create index if not exists idx_listado_personas_rellamar on public.listado_personas (rellamar_el);

create table if not exists public.listado_llamadas (
  id                  bigint generated by default as identity primary key,
  persona_id          bigint not null references public.listado_personas(id) on delete cascade,
  fecha               timestamptz not null default now(),
  notas               text,
  incluir_en_informe  boolean not null default true,
  created_at          timestamptz not null default now()
);
create index if not exists idx_listado_llamadas_fecha   on public.listado_llamadas (fecha);
create index if not exists idx_listado_llamadas_persona on public.listado_llamadas (persona_id);

-- ---------------------------------------------------------------------
-- 9. EQUIPO (reclutas y agentes), CALENDARIO, OBJETIVOS, PLANTILLAS,
--    PROMOCIONES y COMISIONES

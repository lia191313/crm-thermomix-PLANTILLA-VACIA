-- 11. SEGURIDAD: solo con la sesión iniciada en la app
-- =====================================================================
do $$
declare
  t text;
begin
  foreach t in array array[
    'contacts','interactions','recordatorios','ventas','demos',
    'rellamar','rellamadas','prioritarios','dashboard_snooze',
    'anotaciones','historial_llamadas','grupos','contacto_grupos','leads_redes',
    'listados','listado_personas','listado_llamadas','push_subscriptions',
    'equipo','equipo_notas','eventos','objetivos','plantillas','promociones','comisiones'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists solo_usuaria_logueada on public.%I', t);
    execute format(
      'create policy solo_usuaria_logueada on public.%I for all to authenticated using (true) with check (true)', t);
    -- Permisos de la app (con sesión iniciada). Sin sesión: nada.
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('revoke all on public.%I from anon', t);
  end loop;
end $$;

grant usage, select on all sequences in schema public to authenticated;


-- =====================================================================
-- 12. ACTUALIZACIÓN EN DIRECTO (si cambias algo en el móvil, el ordenador
--     lo ve al momento). Si esto fallara, la app funciona igual.
-- =====================================================================
do $$
declare
  t text;
begin
  foreach t in array array['interactions','rellamar'] loop
    if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
       and not exists (select 1 from pg_publication_tables
                       where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
exception when others then
  raise notice 'Realtime no activado (no pasa nada): %', sqlerrm;
end $$;


-- =====================================================================
-- COMPROBACIÓN: deben salir 25 filas, todas con rls_activo = true
-- =====================================================================
select c.relname as tabla, c.relrowsecurity as rls_activo
from pg_class c
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relkind = 'r'
  and c.relname in (
    'contacts','interactions','recordatorios','ventas','demos',
    'rellamar','rellamadas','prioritarios','dashboard_snooze',
    'anotaciones','historial_llamadas','grupos','contacto_grupos','leads_redes',
    'listados','listado_personas','listado_llamadas','push_subscriptions',
    'equipo','equipo_notas','eventos','objetivos','plantillas','promociones','comisiones')
order by c.relname;
